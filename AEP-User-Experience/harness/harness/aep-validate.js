#!/usr/bin/env node
// @ts-check

/**
 * AEP 2.9 Agent Harness - Automated Validation Script
 *
 * Scans the project source files and checks every rendered element
 * against the AEP registry, scene graph and theme.
 *
 * Usage: node harness/aep-validate.js [--src=path] [--config=path]
 *
 * Exit codes:
 *   0 = no blocking violations
 *   1 = CRITICAL or HIGH violations found (printed to stdout)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import * as temporal from './aep-temporal-validate.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));

// ---------------------------------------------------------------------------
// Configuration
// ---------------------------------------------------------------------------

export const DEFAULT_SRC = './src';
export const DEFAULT_CONFIG = '.';
export const FILE_EXTENSIONS = ['.tsx', '.jsx', '.ts', '.js', '.vue', '.svelte', '.html'];

export const SEVERITY = /** @type {const} */ ({ CRITICAL: 'CRITICAL', HIGH: 'HIGH', MEDIUM: 'MEDIUM', LOW: 'LOW' });

/** @typedef {typeof SEVERITY[keyof typeof SEVERITY]} Severity */

/**
 * @typedef {object} Violation
 * @property {Severity} severity
 * @property {string} file
 * @property {number} line
 * @property {string} rule
 * @property {string} message
 */

/**
 * @typedef {object} WritingRule
 * @property {string} id
 * @property {number[]} [code_points]
 */

/** @typedef {Record<string, unknown>} Json */

/**
 * @param {unknown} v
 * @returns {v is Json}
 */
function isObject(v) {
    return v !== null && typeof v === 'object' && !Array.isArray(v);
}

/**
 * The one writing rule table, generated by the compiled wall set in the admit
 * crate. Every prose dash verdict in this harness reads this table.
 * @returns {WritingRule[]}
 */
export function loadWritingRuleTable() {
    const tablePath = path.join(HERE, '..', '..', '..', 'AEP-Components', 'admit', 'rules', 'writing-rules.json');
    /** @type {unknown} */
    const parsed = JSON.parse(fs.readFileSync(tablePath, 'utf8'));
    const rules = isObject(parsed) ? parsed.rules : undefined;
    if (!Array.isArray(rules)) throw new Error(`${tablePath} holds no rules list`);
    return rules.filter(isObject).map((r) => ({
        id: String(r.id),
        code_points: Array.isArray(r.code_points)
            ? r.code_points.filter(/** @returns {p is number} */ (p) => Number.isInteger(p))
            : [],
    }));
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/**
 * @param {string} filepath
 * @returns {unknown}
 */
export function loadJSON(filepath) {
    try {
        return JSON.parse(fs.readFileSync(filepath, 'utf8'));
    } catch {
        return null;
    }
}

/**
 * @param {string} filepath
 * @returns {unknown}
 */
export function loadYAML(filepath) {
    try {
        return yaml.load(fs.readFileSync(filepath, 'utf8'));
    } catch {
        return null;
    }
}

/**
 * Every file below dir with one of the extensions, skipping node_modules,
 * .next and dist. Symbolic links are not followed.
 * @param {string} dir
 * @param {string[]} extensions
 * @returns {string[]}
 */
export function walkDir(dir, extensions) {
    /** @type {string[]} */
    const results = [];
    if (!fs.existsSync(dir)) return results;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        if (entry.name === 'node_modules' || entry.name === '.next' || entry.name === 'dist') continue;
        const fullPath = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            results.push(...walkDir(fullPath, extensions));
        } else if (entry.isFile() && extensions.some(ext => entry.name.endsWith(ext))) {
            results.push(fullPath);
        }
    }
    return results;
}

/**
 * @param {string} content
 * @param {number} index
 */
function lineOf(content, index) {
    return content.substring(0, index).split('\n').length;
}

/** @param {string} line */
function isCommentLine(line) {
    const t = line.trim();
    return t.startsWith('//') || t.startsWith('*');
}

/** @param {string} s */
function escapeRegExp(s) {
    return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Each JSON object line of the evidence ledger with its line number.
 * Malformed lines are skipped.
 * @param {string} ledgerPath
 * @returns {{ line: number, entry: Json }[]}
 */
export function readLedger(ledgerPath) {
    if (!fs.existsSync(ledgerPath)) return [];
    let content;
    try {
        content = fs.readFileSync(ledgerPath, 'utf8');
    } catch {
        return [];
    }
    /** @type {{ line: number, entry: Json }[]} */
    const out = [];
    content.split('\n').forEach((raw, i) => {
        if (raw.trim().length === 0) return;
        try {
            /** @type {unknown} */
            const entry = JSON.parse(raw);
            if (isObject(entry)) out.push({ line: i + 1, entry });
        } catch {
            // A malformed line is not a violation.
        }
    });
    return out;
}

/** @param {unknown} v */
function text(v) {
    return typeof v === 'string' || typeof v === 'number' ? String(v) : '';
}

/**
 * @param {string} s
 * @returns {Severity}
 */
function toSeverity(s) {
    if (s === 'CRITICAL') return SEVERITY.CRITICAL;
    if (s === 'HIGH') return SEVERITY.HIGH;
    if (s === 'MEDIUM') return SEVERITY.MEDIUM;
    return SEVERITY.LOW;
}

// ---------------------------------------------------------------------------
// Validators
// ---------------------------------------------------------------------------

const LEDGER_FILE = '.claude/aep-evidence.jsonl';

export class AEPValidator {
    /**
     * @param {string} configDir
     * @param {string} srcDir
     * @param {WritingRule[]} [writingRules]
     */
    constructor(configDir, srcDir, writingRules) {
        /** @type {Violation[]} */
        this.violations = [];
        this.scene = loadJSON(path.join(configDir, 'aep-scene.json'));
        this.registry = loadYAML(path.join(configDir, 'aep-registry.yaml'));
        const theme = loadYAML(path.join(configDir, 'aep-theme.yaml'));
        /** @type {Json} */
        this.theme = isObject(theme) ? theme : {};
        this.srcDir = srcDir;
        this.writingRules = writingRules ?? loadWritingRuleTable();
        this.ledgerPath = path.join(srcDir, '..', LEDGER_FILE);

        /** @type {Set<string>} */
        this.sceneXids = new Set();
        const elements = isObject(this.scene) ? this.scene.elements : undefined;
        if (Array.isArray(elements)) {
            for (const el of elements) {
                if (isObject(el) && typeof el.id === 'string') this.sceneXids.add(el.id);
            }
        }

        /** @type {Set<string>} */
        this.registryXids = new Set();
        if (isObject(this.registry)) {
            for (const key of Object.keys(this.registry)) {
                if (key.startsWith('xid:')) this.registryXids.add(key);
            }
        }

        /** @type {Set<string>} */
        this.skinBindings = new Set();
        if (isObject(this.theme.component_styles)) {
            for (const key of Object.keys(this.theme.component_styles)) this.skinBindings.add(key);
        }

        /** @type {Set<string>} */
        this.paletteColors = new Set();
        if (isObject(this.theme.colours)) {
            for (const val of Object.values(this.theme.colours)) {
                if (typeof val === 'string') this.paletteColors.add(val.toLowerCase());
            }
        }

        /** @type {Json} */
        this.designRules = isObject(this.theme.design_rules) ? this.theme.design_rules : {};

        /** @type {string[]} */
        this.bannedTerms = Array.isArray(this.theme.banned_terms)
            ? this.theme.banned_terms.filter(/** @returns {t is string} */ (t) => typeof t === 'string' && t.length > 0)
            : [];

        // dynAEP-TA: temporal authority configuration
        this.temporalConfig = temporal.loadTemporalConfig(configDir);
    }

    /**
     * @param {Severity} severity
     * @param {string} file
     * @param {number} line
     * @param {string} rule
     * @param {string} message
     */
    addViolation(severity, file, line, rule, message) {
        this.violations.push({ severity, file, line, rule, message });
    }

    /**
     * Check 1: data-aep-id attributes match registry and scene.
     * @param {string} file
     * @param {string} content
     */
    checkElementRegistration(file, content) {
        const aepIdRegex = /data-aep-id[={"']+([^"'}]+)/g;
        let match;
        while ((match = aepIdRegex.exec(content)) !== null) {
            const xid = (match[1] ?? '').trim();
            const lineNum = lineOf(content, match.index);
            if (this.registryXids.size > 0 && !this.registryXids.has(xid)) {
                this.addViolation(SEVERITY.CRITICAL, file, lineNum, 'ELEMENT_NOT_REGISTERED',
                    `data-aep-id="${xid}" not found in aep-registry.yaml`);
            }
            if (this.sceneXids.size > 0 && !this.sceneXids.has(xid)) {
                this.addViolation(SEVERITY.HIGH, file, lineNum, 'ELEMENT_NOT_IN_SCENE',
                    `data-aep-id="${xid}" not found in aep-scene.json`);
            }
        }
    }

    /**
     * Check 2: hardcoded colors.
     * @param {string} file
     * @param {string} content
     */
    checkHardcodedColors(file, content) {
        if (file.includes('aep-theme') || file.includes('aep-registry')) return;
        const lines = content.split('\n');
        const hexRegex = /#[0-9a-fA-F]{6}\b/g;
        let match;
        while ((match = hexRegex.exec(content)) !== null) {
            const hex = match[0].toLowerCase();
            const lineNum = lineOf(content, match.index);
            const line = lines[lineNum - 1] ?? '';
            if (isCommentLine(line)) continue;
            // Declarations of the palette itself
            if (line.includes('palette') || line.includes('PALETTE') || line.includes('colors')) continue;
            if (this.paletteColors.size > 0 && !this.paletteColors.has(hex)) {
                this.addViolation(SEVERITY.MEDIUM, file, lineNum, 'HARDCODED_COLOR',
                    `Color ${hex} is not in the AEP palette. Use a theme token.`);
            }
        }
    }

    /**
     * Check 3: border radius violations.
     * @param {string} file
     * @param {string} content
     */
    checkBorderRadius(file, content) {
        const rule = this.designRules.border_radius;
        if (!rule) return;
        const lines = content.split('\n');
        const radiusRegex = /border[Rr]adius[:\s]+['"]?(\d+)/g;
        let match;
        while ((match = radiusRegex.exec(content)) !== null) {
            const value = parseInt(match[1] ?? '0', 10);
            const lineNum = lineOf(content, match.index);
            const line = lines[lineNum - 1] ?? '';
            if (value <= 0 || value === 50) continue;
            const isException = line.includes('comm-panel') || line.includes('commPanel') ||
                line.includes('50%') || line.includes('circle');
            if (!isException) {
                this.addViolation(SEVERITY.HIGH, file, lineNum, 'BORDER_RADIUS_VIOLATION',
                    `border-radius: ${value}px found. AEP design rules: ${text(rule)}`);
            }
        }
    }

    /**
     * Check 4: box shadow violations. A value of none is allowed.
     * @param {string} file
     * @param {string} content
     */
    checkBoxShadow(file, content) {
        const shadows = this.designRules.shadows;
        if (!(typeof shadows === 'string' && shadows.includes('Never'))) return;
        const lines = content.split('\n');
        const shadowRegex = /box[Ss]hadow[:\s]+['"]?([^'";,\s}]+)/g;
        let match;
        while ((match = shadowRegex.exec(content)) !== null) {
            const lineNum = lineOf(content, match.index);
            const line = lines[lineNum - 1] ?? '';
            if ((match[1] ?? '').toLowerCase() === 'none') continue;
            if (isCommentLine(line)) continue;
            this.addViolation(SEVERITY.HIGH, file, lineNum, 'BOX_SHADOW_VIOLATION',
                'box-shadow found. AEP design rules forbid shadows. Use glassmorphism.');
        }
    }

    /**
     * Check 5: hardcoded font families.
     * @param {string} file
     * @param {string} content
     */
    checkHardcodedFonts(file, content) {
        if (file.includes('aep-theme') || file.includes('typography')) return;
        const fontRegex = /fontFamily[:\s]+['"]([^'"]+)['"]/g;
        let match;
        while ((match = fontRegex.exec(content)) !== null) {
            const font = match[1] ?? '';
            if (font.includes('var(') || font.includes('T.')) continue;
            this.addViolation(SEVERITY.MEDIUM, file, lineOf(content, match.index), 'HARDCODED_FONT',
                `Hardcoded fontFamily "${font}". Use a typography token from aep-theme.`);
        }
    }

    /**
     * Check 6: internal terminology in user-facing strings. A term is matched
     * as text, so a term holding regex syntax neither breaks nor widens it.
     * @param {string} file
     * @param {string} content
     */
    checkInternalTerminology(file, content) {
        const lines = content.split('\n');
        for (const term of this.bannedTerms) {
            // Lookarounds in place of word boundaries, so a term that ends in a
            // sign such as c++ matches too.
            const pattern = new RegExp(`['"]([^'"]*(?<!\\w)${escapeRegExp(term)}(?!\\w)[^'"]*)['"]`, 'gi');
            let match;
            while ((match = pattern.exec(content)) !== null) {
                const lineNum = lineOf(content, match.index);
                const line = lines[lineNum - 1] ?? '';
                if (line.includes('data-aep-id')) continue;
                if (isCommentLine(line)) continue;
                if (line.includes('const ') || line.includes('let ') || line.includes('type ')) continue;
                this.addViolation(SEVERITY.HIGH, file, lineNum, 'INTERNAL_TERMINOLOGY',
                    `Banned term "${term}" found in user-facing string: "${(match[1] ?? '').substring(0, 50)}..."`);
            }
        }
    }

    /**
     * Check 7: skin binding references resolve.
     * @param {string} file
     * @param {string} content
     */
    checkSkinBindings(file, content) {
        const bindingRegex = /skin_binding[:\s]+['"]?(\w+)/g;
        let match;
        while ((match = bindingRegex.exec(content)) !== null) {
            const binding = match[1] ?? '';
            if (this.skinBindings.size > 0 && !this.skinBindings.has(binding)) {
                this.addViolation(SEVERITY.HIGH, file, lineOf(content, match.index), 'SKIN_BINDING_MISSING',
                    `skin_binding "${binding}" not found in aep-theme.yaml component_styles`);
            }
        }
    }

    /**
     * Check 8: forbidden typographic dashes, read from the one writing rule table.
     * @param {string} file
     * @param {string} content
     */
    checkDashes(file, content) {
        for (const rule of this.writingRules) {
            if (rule.id !== 'no_em_dashes' && rule.id !== 'no_en_dashes') continue;
            const code = rule.id === 'no_em_dashes' ? 'EM_DASH' : 'EN_DASH';
            for (const point of rule.code_points ?? []) {
                const ch = String.fromCodePoint(point);
                const label = `U+${point.toString(16).toUpperCase()}`;
                let idx = content.indexOf(ch);
                while (idx !== -1) {
                    this.addViolation(SEVERITY.LOW, file, lineOf(content, idx), code,
                        `Forbidden dash ${label} found. Use - instead.`);
                    idx = content.indexOf(ch, idx + 1);
                }
            }
        }
    }

    /**
     * Run all checks.
     * @param {(line: string) => void} [log]
     */
    validate(log = console.log) {
        const files = walkDir(this.srcDir, FILE_EXTENSIONS);
        const tc = this.temporalConfig;

        log('AEP 2.9 Validation');
        log(`  Source: ${this.srcDir}`);
        log(`  Files: ${files.length}`);
        log(`  Registry entries: ${this.registryXids.size}`);
        log(`  Scene elements: ${this.sceneXids.size}`);
        log(`  Skin bindings: ${this.skinBindings.size}`);
        log(`  Palette colors: ${this.paletteColors.size}`);
        log(`  Temporal authority: ${tc.enabled ? 'ENABLED' : 'DISABLED'}`);
        log(`  Perception governance: ${tc.perception_governance.enabled ? 'ENABLED' : 'DISABLED'}`);
        log(`  Perception modalities: ${temporal.listModalities().join(', ')}`);
        log('');

        // Phase 1: temporal validation runs before the structural checks.
        if (tc.enabled) this.checkTemporalViolations();
        // Phase 2: perception validation runs between temporal and structural.
        if (tc.perception_governance.enabled) this.checkPerceptionViolations();

        // Phase 3: structural validation
        for (const file of files) {
            const content = fs.readFileSync(file, 'utf8');
            const relPath = path.relative(process.cwd(), file);
            this.checkElementRegistration(relPath, content);
            this.checkHardcodedColors(relPath, content);
            this.checkBorderRadius(relPath, content);
            this.checkBoxShadow(relPath, content);
            this.checkHardcodedFonts(relPath, content);
            this.checkInternalTerminology(relPath, content);
            this.checkSkinBindings(relPath, content);
            this.checkDashes(relPath, content);
            if (tc.enabled) this.checkLocalClockUsage(relPath, content);
        }

        this.checkCrossReferences();
        this.checkEvidenceLedger();
        this.checkTrustViolations();
        this.checkRecoveryAndScanners();

        return this.violations;
    }

    checkCrossReferences() {
        for (const xid of this.registryXids) {
            if (this.sceneXids.size > 0 && !this.sceneXids.has(xid)) {
                this.addViolation(SEVERITY.HIGH, 'aep-registry.yaml', 0, 'REGISTRY_NOT_IN_SCENE',
                    `${xid} is in registry but not in scene graph`);
            }
        }
        for (const xid of this.sceneXids) {
            if (this.registryXids.size > 0 && !this.registryXids.has(xid)) {
                this.addViolation(SEVERITY.HIGH, 'aep-scene.json', 0, 'SCENE_NOT_IN_REGISTRY',
                    `${xid} is in scene graph but not in registry`);
            }
        }
    }

    /** Check 9: evidence ledger integrity. */
    checkEvidenceLedger() {
        for (const { line, entry } of readLedger(this.ledgerPath)) {
            if (entry.verdict === 'blocked' && entry.action !== 'rollback') {
                this.addViolation(SEVERITY.CRITICAL, LEDGER_FILE, line, 'GATEWAY_POLICY_FAIL',
                    `AgentGateway blocked action on ${text(entry.target)}: ${text(entry.reason) || 'policy failure'}`);
            }
            if (entry.action === 'rollback' && entry.restored !== true) {
                this.addViolation(SEVERITY.MEDIUM, LEDGER_FILE, line, 'ROLLBACK_INCOMPLETE',
                    `Rollback recorded for ${text(entry.target)} but restoration not confirmed`);
            }
        }
    }

    /** Check 10: GAP agent_permission violations. */
    checkTrustViolations() {
        for (const { line, entry } of readLedger(this.ledgerPath)) {
            const who = `agent '${text(entry.agent_id) || 'unbound'}' may not '${text(entry.action)}'`;
            if (entry.trust_violation) {
                this.addViolation(SEVERITY.CRITICAL, LEDGER_FILE, line, 'TRUST_VIOLATION',
                    `GAP dimension agent_permission closed: ${who}`);
            }
            if (entry.kill_switch_active) {
                this.addViolation(SEVERITY.CRITICAL, LEDGER_FILE, line, 'KILL_SWITCH_ACTIVE',
                    'Operator kill switch is engaged - all mutations blocked');
            }
            if (entry.covenant_forbid) {
                this.addViolation(SEVERITY.HIGH, LEDGER_FILE, line, 'COVENANT_FORBID',
                    `Action matched forbid rule: ${text(entry.covenant_rule) || text(entry.reason) || 'unknown rule'}`);
            }
            if (entry.intent_drift) {
                this.addViolation(SEVERITY.HIGH, LEDGER_FILE, line, 'INTENT_DRIFT',
                    `Agent behaviour deviated from baseline (drift score: ${text(entry.drift_score) || '?'})`);
            }
            if (entry.merkle_fail) {
                this.addViolation(SEVERITY.HIGH, LEDGER_FILE, line, 'MERKLE_INTEGRITY_FAIL',
                    'Ledger Merkle proof verification failed - possible tampering');
            }
        }
    }

    /** Check 11: recovery and scanner entries. */
    checkRecoveryAndScanners() {
        for (const { line, entry } of readLedger(this.ledgerPath)) {
            if (entry.type === 'scanner:finding' && entry.severity === 'hard') {
                this.addViolation(SEVERITY.CRITICAL, LEDGER_FILE, line, 'SCANNER_HARD_FINDING',
                    `Scanner "${text(entry.scanner) || 'unknown'}" found hard violation: ${text(entry.details) || text(entry.rule) || 'unknown'}`);
            }
            if (entry.type === 'recovery:exhausted') {
                this.addViolation(SEVERITY.HIGH, LEDGER_FILE, line, 'RECOVERY_EXHAUSTED',
                    `Recovery exhausted after ${text(entry.attempts) || '?'} attempts for rule: ${text(entry.rule) || 'unknown'}`);
            }
        }
    }

    /** Check 12: temporal event violations in the evidence ledger (dynAEP-TA). */
    checkTemporalViolations() {
        temporal.resetCausalState();
        for (const { line, entry } of readLedger(this.ledgerPath)) {
            if (entry.type === 'temporal_validation' && isObject(entry.data)) {
                const result = temporal.validateTemporalEvent({
                    bridgeTimeMs: entry.data.bridgeTimeMs,
                    agentTimeMs: entry.data.agentTimeMs,
                    agentId: entry.data.agentId,
                    causalPosition: entry.data.causalPosition,
                }, this.temporalConfig);
                for (const v of result.violations) {
                    this.addViolation(toSeverity(v.severity), LEDGER_FILE, line,
                        'TEMPORAL_' + v.type.toUpperCase(), v.message);
                }
            }
            if (entry.type === 'temporal_violation') {
                const severity = entry.severity === 'CRITICAL' ? SEVERITY.CRITICAL
                    : entry.severity === 'HIGH' ? SEVERITY.HIGH : SEVERITY.MEDIUM;
                this.addViolation(severity, LEDGER_FILE, line, 'TEMPORAL_VIOLATION',
                    text(entry.message) || `Temporal violation: ${text(entry.violation_type) || 'unspecified'}`);
            }
        }
    }

    /** Check 13: perception annotation violations in the evidence ledger (dynAEP-TA-P). */
    checkPerceptionViolations() {
        for (const { line, entry } of readLedger(this.ledgerPath)) {
            if (entry.type === 'perception_governance' && isObject(entry.data)) {
                const data = entry.data;
                /** @type {Record<string, unknown>} */
                const annotations = {};
                if (typeof data.originalSyllableRate === 'number') annotations.syllable_rate = data.originalSyllableRate;
                if (typeof data.originalTurnGapMs === 'number') annotations.turn_gap_ms = data.originalTurnGapMs;
                if (isObject(data.originalAnnotations)) Object.assign(annotations, data.originalAnnotations);

                const modality = data.modality;
                if (typeof modality === 'string' && Object.keys(annotations).length > 0) {
                    const result = temporal.validatePerceptionAnnotation(modality, annotations,
                        this.temporalConfig.perception_governance);
                    for (const v of result.violations) {
                        const severity = v.type === 'hard_violation' ? SEVERITY.CRITICAL
                            : v.type === 'soft_violation' ? SEVERITY.MEDIUM : SEVERITY.HIGH;
                        this.addViolation(severity, LEDGER_FILE, line, 'PERCEPTION_' + v.type.toUpperCase(), v.message);
                    }
                }
            }
            if (entry.type === 'perception_violation') {
                const severity = entry.severity === 'hard' ? SEVERITY.CRITICAL : SEVERITY.MEDIUM;
                this.addViolation(severity, LEDGER_FILE, line, 'PERCEPTION_VIOLATION',
                    text(entry.message) || `Perception violation on ${text(entry.modality) || 'unknown'}: ${text(entry.parameter) || 'unspecified'}`);
            }
        }
    }

    /**
     * Check 14: local clock usage in governed code paths (dynAEP-TA). A line
     * marked temporal:fallback uses the local clock on purpose.
     * @param {string} file
     * @param {string} content
     */
    checkLocalClockUsage(file, content) {
        if (file.includes('aep-temporal-validate') || file.includes('aep-safety-guard') ||
            file.includes('.test.') || file.includes('.spec.') || file.includes('node_modules')) return;

        const patterns = [
            { regex: /Date\.now\(\)/g, name: 'Date.now()' },
            { regex: /new\s+Date\(\s*\)/g, name: 'new Date()' },
            { regex: /performance\.now\(\)/g, name: 'performance.now()' },
        ];
        const lines = content.split('\n');
        for (const pat of patterns) {
            let match;
            while ((match = pat.regex.exec(content)) !== null) {
                const lineNum = lineOf(content, match.index);
                const line = lines[lineNum - 1] ?? '';
                if (isCommentLine(line)) continue;
                if (line.includes('temporal:fallback')) continue;
                this.addViolation(SEVERITY.MEDIUM, file, lineNum, 'LOCAL_CLOCK_USAGE',
                    `${pat.name} found in governed code. Use dynaep_temporal_query(authoritative_time) instead.`);
            }
        }
    }

    /**
     * Print the report and return the exit code.
     * @param {(line: string) => void} [log]
     * @returns {0 | 1}
     */
    report(log = console.log) {
        if (this.violations.length === 0) {
            log('AEP VALIDATION PASSED. Zero violations.');
            return 0;
        }

        log(`AEP VALIDATION: ${this.violations.length} violation(s) found.\n`);
        for (const severity of [SEVERITY.CRITICAL, SEVERITY.HIGH, SEVERITY.MEDIUM, SEVERITY.LOW]) {
            const items = this.violations.filter((v) => v.severity === severity);
            if (items.length === 0) continue;
            log(`  ${severity} (${items.length}):`);
            for (const v of items) log(`    ${v.file}:${v.line}  [${v.rule}] ${v.message}`);
            log('');
        }

        const critical = this.violations.filter((v) => v.severity === SEVERITY.CRITICAL).length;
        const high = this.violations.filter((v) => v.severity === SEVERITY.HIGH).length;
        if (critical > 0 || high > 0) {
            log(`BLOCKING: ${critical} CRITICAL + ${high} HIGH violations must be fixed.`);
            return 1;
        }
        log('NON-BLOCKING: Only MEDIUM/LOW violations. Commit allowed but fix soon.');
        return 0;
    }
}

/**
 * The value of a --name=value argument. The value keeps every = after the first.
 * @param {string[]} args
 * @param {string} name
 * @returns {string | undefined}
 */
export function argValue(args, name) {
    const prefix = `--${name}=`;
    const arg = args.find((a) => a.startsWith(prefix));
    return arg === undefined ? undefined : arg.slice(prefix.length);
}

/**
 * @param {string[]} args
 * @returns {0 | 1}
 */
export function main(args) {
    const validator = new AEPValidator(argValue(args, 'config') ?? DEFAULT_CONFIG, argValue(args, 'src') ?? DEFAULT_SRC);
    validator.validate();
    return validator.report();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    process.exitCode = main(process.argv.slice(2));
}
